const TABLE: ReadonlyMap<number, number> = new Map(MAC_TO_UIOHOOK);

/** uiohook code for a mac virtual key code, or `null` when there is none. */
export function macKeyCodeToUiohook(macKeyCode: number): number | null {
  return TABLE.get(macKeyCode) ?? null;
}

/** Every mapped mac key code (for tests). */
export const MAPPED_MAC_KEY_CODES: readonly number[] = MAC_TO_UIOHOOK.map(([mac]) => mac);
